def test_tools_md_lists_usage_from_docstrings(root):
    F.make_tool(root, "frame_qa", "python tools/frame_qa.py INPUT.mp4 [--json]")
    F.write(root / "tools" / "multi.py", '"""Multi-line usage tool.\n\nUsage: python tools/multi.py A\n    python tools/multi.py B --flag\n\nMore text.\n"""\n')
    report, text = T.run(root)
    assert report.status == C.PASS and report.stats["tools"] == 2
    assert "`frame_qa`" in text and "python tools/frame_qa.py INPUT.mp4 [--json]" in text
    assert "python tools/multi.py A" in text and "python tools/multi.py B --flag" in text
    assert text.startswith("<!-- GENERATED by scripts/gen_tools_md.py")
    assert "None." in text.split("## Missing Usage docstring")[1]


def test_tools_are_parsed_never_executed(root):
    marker = root / "executed.txt"
    F.write(root / "tools" / "evil.py", f'"""Evil.\n\nUsage: python tools/evil.py\n"""\nopen({str(marker)!r}, "w").write("ran")\nraise SystemExit(7)\n')
    report, text = T.run(root)
    assert not marker.exists() and "evil" in text


def test_missing_usage_is_reported_and_strict_fails(root):
    F.write(root / "tools" / "nodoc.py", "print('x')\n")
    F.write(root / "tools" / "nousage.py", '"""Does a thing."""\n')
    F.write(root / "tools" / "broken.py", "def (:\n")
    report, text = T.run(root)
    assert report.status == C.WARN and len(report.warns) == 3
    missing = text.split("## Missing Usage docstring")[1]
    assert "nodoc.py" in missing and "nousage.py" in missing and "broken.py" in missing
    strict, _ = T.run(root, strict_usage=True)
    assert strict.status == C.FAIL


def test_private_and_init_files_are_skipped(root):
    F.make_tool(root, "real")
