def test_system_md_is_deterministic_and_utf8(root):
    F.make_repo(root)
    F.write(root / "agent-content/playbooks/wf-02-hebrew.md", "# תהליך עריכה בעברית\n")
    first = S.render(root)[0]
    assert first == S.render(root)[0] and "תהליך עריכה בעברית" in first
    out = F.run_cli(SYSTEM_CLI, "--root", root)
    assert out.returncode == 0
    assert (root / "SYSTEM.md").read_bytes().decode("utf-8") == first
    assert not (root / "SYSTEM.md").read_bytes().startswith(b"\xef\xbb\xbf")


def test_system_cli_exit_codes_and_json(root):
    F.make_repo(root)
    t = time.monotonic()
    assert F.run_cli(SYSTEM_CLI, "--help").returncode == 0 and time.monotonic() - t < 3
    shown = F.run_cli(SYSTEM_CLI, "--root", root, "--stdout")
    assert shown.returncode == 0 and "# SYSTEM catalogue" in shown.stdout and not (root / "SYSTEM.md").exists()
    data = json.loads(F.run_cli(SYSTEM_CLI, "--root", root, "--check", "--json").stdout)
    assert data["status"] == "FAIL" and data["exit"] == 1
    empty = root.parent / "e"
    empty.mkdir()
    assert F.run_cli(SYSTEM_CLI, "--root", empty).returncode == 0
    assert F.run_cli(SYSTEM_CLI, "--root", empty, "--strict").returncode == 3
    assert F.run_cli(SYSTEM_CLI, "--root", root / "nope").returncode == 2
