def test_system_md_catalogue_content_and_order(root):
    F.make_repo(root)
    F.write(root / "agent-content" / "techniques" / "clean-smooth-motion.md", "---\ntitle: Clean smooth motion\n---\n# ignored heading\n")
    F.write(root / "agent-content" / "benchmarks" / "talking-head.rubric.md", "# Talking head rubric\n")
    F.write(root / "agent-content" / "references" / "platform-specs.md", "# Platform specs (dated)\n")
    report, text = S.run(root)
    assert report.fails == [] and report.stats["skills"] == 2
    assert "## Skills (2)" in text and "`demo-skill`" in text and "`second-skill`" in text
    assert "Cut and caption a talking-head clip into a vertical reel." in text
    assert "Clean smooth motion" in text and "Talking head rubric" in text and "Platform specs (dated)" in text
    assert "`tools/frame_qa.py`" in text and "python tools/frame_qa.py INPUT.mp4 [--json]" in text
    pipeline = text.split("## Ideal pipeline")[1]
    assert pipeline.index("wf-00-intake") < pipeline.index("wf-01-build")
    assert "model evaluation has not been run" in text


